import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = path.join(root, 'supabase/migrations');
const files = readdirSync(directory).filter(name => /^\d+_.+\.sql$/.test(name)).sort();
const bundle = '-- GENERATED by scripts/build_migration_bundle.mjs. Do not edit directly.\n'
  + '-- Fresh database only. Do not also apply individual migrations to that database.\n\n'
  + files.map(name => `/* FILE: ${name} */\n${readFileSync(path.join(directory, name), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trim()}\n`).join('\n');
const target = path.join(directory, 'apply_all.sql');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== bundle) {
    throw new Error('apply_all.sql is stale. Run node scripts/build_migration_bundle.mjs');
  }
  console.log(`PASS bundle parity: ${files.length} migrations`);
} else {
  writeFileSync(target, bundle);
  console.log(`Generated apply_all.sql from ${files.length} migrations`);
}
